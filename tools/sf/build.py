"""Renders the SF Symbols named in icons.json into src/icons.css: one mask variable per symbol,
and a rule per selector that hides Discord's own icon and draws the symbol in its place with
currentColor. Rendering needs macOS (swift and SF Symbols) and ImageMagick; run node build.mjs
afterwards to rebuild the bundle."""
import base64, json, pathlib, subprocess, sys, tempfile, textwrap

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "src" / "icons.css"
CANVAS, POINT, WEIGHT = 112, 64, "regular"
# Symbols this macOS only draws as a filled shape; build.py keeps their main layer and turns the
# filled secondary layer into a ring, so they match the outline style of the rest.
OUTLINE = {"face.smiling"}

cfg = json.loads((HERE / "icons.json").read_text())
symbols = sorted({s for g in cfg["groups"] for s in g["items"].values()})

with tempfile.TemporaryDirectory() as tmp:
    res = subprocess.run(["swift", str(HERE / "render.swift"), tmp, str(CANVAS), str(POINT), WEIGHT, *symbols],
                         capture_output=True, text=True, check=True)
    missing = [l.split()[1] for l in res.stdout.splitlines() if l.startswith("MISSING")]
    if missing:
        sys.exit("missing symbols: " + ", ".join(missing))
    for s in OUTLINE & set(symbols):
        h = pathlib.Path(tmp) / "h"; h.mkdir(exist_ok=True)
        subprocess.run(["swift", str(HERE / "render.swift"), str(h), str(CANVAS), str(POINT), WEIGHT, s],
                       check=True, capture_output=True, env={**__import__("os").environ, "SF_MODE": "hierarchical"})
        src, dst = h / f"{s}.png", pathlib.Path(tmp) / f"{s}.png"
        disk, ring, feat, mask = (h / f"{s}.{n}.png" for n in ("disk", "ring", "feat", "mask"))
        m = lambda *a: subprocess.run(["magick", *map(str, a)], check=True)
        m(src, "-alpha", "extract", "-threshold", "1%", disk)
        m(disk, "(", disk, "-morphology", "Erode", "Disk:5", ")", "-compose", "minus_src", "-composite", ring)
        m(src, "-alpha", "extract", "-threshold", "75%", feat)
        m(ring, feat, "-compose", "lighten", "-composite", "-blur", "0x0.6", mask)
        m("-size", f"{CANVAS}x{CANVAS}", "xc:black", mask, "-alpha", "off", "-compose", "copy_opacity", "-composite", "-strip", dst)
    data = {s: base64.b64encode((pathlib.Path(tmp) / f"{s}.png").read_bytes()).decode() for s in symbols}

var = lambda s: "--sf-" + s.replace(".", "-")


def strip_has(sel):
    """sel without its :has() tests, :not(:has()) included."""
    out, i = "", 0
    while i < len(sel):
        for opener in (":not(:has(", ":has("):
            if sel.startswith(opener, i):
                depth, j = opener.count("("), i + len(opener)
                while depth:
                    depth += {"(": 1, ")": -1}.get(sel[j], 0)
                    j += 1
                i = j
                break
        else:
            out += sel[i]
            i += 1
    return out


def hide_rules(sels, parts):
    """Rules hiding Discord's own icon (parts, inside each selector). A selector found with :has()
    can't reach into its children: a :has() above the styled element makes every DOM change in
    the app restyle whole lists. It sets --vg-sf-swap instead, and the hiding asks for the flag
    with a style query."""
    plain = [s for s in sels if ":has(" not in s]
    found = [strip_has(s) for s in sels if ":has(" in s]
    rules = []
    if plain:
        rules.append(",\n".join(f"{s} {p}" for s in plain for p in parts) + " {\n  opacity: 0 !important;\n}")
    if found:
        rule = ",\n".join(f"{s} {p}" for s in found for p in parts) + " {\n  opacity: 0 !important;\n}"
        rules.append("@container style(--vg-sf-swap: 1) {\n" + textwrap.indent(rule, "  ") + "\n}")
    return rules


head = ["/* Generated by tools/sf/build.py from tools/sf/icons.json; edit those, not this file. */", ":root {"]
head += [f'  {var(s)}: url("data:image/png;base64,{data[s]}");' for s in symbols]
head.append("}")
out = []
for g in cfg["groups"]:
    for item, sym in g["items"].items():
        sels = [g["scope"].replace("{item}", part.strip()) for part in item.split(", ")]
        sel = ",\n".join(sels)
        after = ",\n".join(f"{s}::after" for s in sels)
        flag = "  --vg-sf-swap: 1;\n" if any(":has(" in s for s in sels) else ""
        out.append(f"{sel} {{\n  position: relative;\n{flag}}}")
        if g.get("anchor") == "left":
            # Rows with an icon column: the symbol is drawn at the column's centre. "hide" names
            # Discord's own icon inside the row when the theme doesn't drop it elsewhere.
            if g.get("hide"):
                out += hide_rules(sels, [g["hide"]])
            before = ",\n".join(f"{s}::before" for s in sels)
            out.append(f"{before} {{\n  content: \"\";\n  position: absolute;\n  left: {g.get('x', 'var(--vg-menu-icon-x)')};\n  top: 50%;\n"
                       f"  width: {g['box']}px;\n  height: {g['box']}px;\n  transform: translate(-50%, -50%);\n"
                       f"  background-color: currentColor;\n  -webkit-mask: var({var(sym)}) center / contain no-repeat;\n"
                       f"  pointer-events: none;\n}}")
            continue
        out += hide_rules(sels, ["svg", '[class*="lottieIcon_"]'])
        out.append(f"{after} {{\n  content: \"\";\n  position: absolute;\n  left: 50%;\n  top: 50%;\n"
                   f"  width: {g['box']}px;\n  height: {g['box']}px;\n  transform: translate(-50%, -50%);\n"
                   f"  background-color: currentColor;\n  -webkit-mask: var({var(sym)}) center / contain no-repeat;\n"
                   f"  pointer-events: none;\n}}")
header = ("/* ==========================================================================\n"
          "   ICONS: SF Symbols\n"
          "   ========================================================================== */\n")
# The rules sit behind the --vg-sf-symbols option; with it off Discord's own icons stay. The
# variables stay outside: :root has no container to query.
body = textwrap.indent("\n".join(out), "  ")
OUT.write_text(header + "\n".join(head) + "\n@container not style(--vg-sf-symbols: off) {\n" + body + "\n}\n")
print(f"{len(symbols)} symbols, {sum(len(v) for v in data.values()) // 1024} KB")
